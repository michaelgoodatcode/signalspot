"""Run the SignalSpot pipeline locally with pandas (no Databricks needed).

Usage (from the repo root):
    python pipeline/build_local.py
    python pipeline/build_local.py --event-start 2026-11-07T09:00 --event-end 2026-11-08T14:00

Produces exactly the same outputs as databricks/01_pipeline.py, so judges can
reproduce the app data from data/raw/ without a Databricks account.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from wifimap.config import (DEFAULT_APP_JSON, DEFAULT_PROCESSED_DIR, DEFAULT_RAW_DIR,  # noqa: E402
                            DEFAULT_SPOTS_PATH)
from wifimap.io import find_raw_files  # noqa: E402
from wifimap.pipeline import run, write_outputs  # noqa: E402


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw-dir", default=str(DEFAULT_RAW_DIR))
    ap.add_argument("--spots", default=str(DEFAULT_SPOTS_PATH))
    ap.add_argument("--app-json", default=str(DEFAULT_APP_JSON))
    ap.add_argument("--processed-dir", default=str(DEFAULT_PROCESSED_DIR))
    ap.add_argument("--event-start", default=None, help="Local time (America/Chicago), e.g. 2026-11-07T09:00")
    ap.add_argument("--event-end", default=None)
    ap.add_argument("--allow-synthetic", action="store_true",
                    help="Keep rows generated by tests/make_synthetic.py (for testing only)")
    args = ap.parse_args(argv)

    files = find_raw_files(args.raw_dir)
    print(f"Found {len(files)} raw file(s) in {args.raw_dir}")
    result = run(files, args.spots, event_start=args.event_start, event_end=args.event_end,
                 allow_synthetic=args.allow_synthetic)
    paths = write_outputs(result, args.app_json, args.processed_dir)
    m = result.app_json["meta"]
    print(f"Kept {m['n_readings']} of {m['n_raw_rows']} rows; {m['n_spots_covered']} spots covered.")
    if m["dropped_by_reason"]:
        print("Removed:", ", ".join(f"{k}={v}" for k, v in m["dropped_by_reason"].items()))
    if m["synthetic"]:
        print("WARNING: output contains SYNTHETIC rows (the app will show a banner).")
    for k, p in paths.items():
        print(f"  wrote {k}: {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
